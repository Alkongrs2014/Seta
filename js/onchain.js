/* =====================================================================
   المعاملات مُقدَّرةٌ من بيانات البتكوين نفسها لا منقولةً من مصدر.

   النسخة الأولى حملت معاملاتٍ شائعة (`2.9065` و`−19.463`) بلا تحقّق،
   فأعطت خطَّ وسطٍ قيمتُه ‎322‎ دولاراً اليوم — أي أن السعر يعلوه ‎237‎
   ضعفاً. فكانت البطاقة تقول «بيعٌ جماعي — فقاعة» دائماً، وهي تناقض
   مضاعفَ ماير ‎1.09‎ وبويل ‎0.93‎ في نفس الشاشة. والتناقضُ الظاهر بين
   بطاقتين هو ما كشف العطب.

   فقُدِّرت المعاملات بانحدارٍ خطّي على `ln(السعر)` مقابل `ln(الأيام)`
   من ‎1,426‎ نقطةً يومية بين ‎2009‎ و‎2026‎ (سلسلة `blockchain.info`
   الكاملة)، بعد إسقاط ما دون ‎0.05$‎ وأوّلِ ‎200‎ يوم — وهي فترةٌ لا سعرَ
   فيها يُعتدّ به فتجذب الانحدار جذباً شديداً.

     a = 3.93583 · b = −22.85231 · انحراف البواقي 0.77

   وعرضُ النطاق ‎0.40‎ اختيارٌ مقيس لا تقدير: بها تُستعمل النطاقات
   التسعة كلُّها على التاريخ (‎52‎ يوماً في الأعلى و‎2‎ في الأدنى)، وبـ
   ‎0.45‎ يبقى النطاق الأخير فارغاً فيصير تسميةً بلا مسمّى.

   وتبقى هذه **وصفاً لموقع السعر من منحناه الطويل، لا تنبّؤاً**. ونموذجُ
   قوّةٍ مُقدَّرٌ بأثرٍ رجعي ينحني مع كل دورةٍ جديدة، فلا يُبنى عليه قرار.
   ===================================================================== */
var RB_A = 3.93583, RB_B = -22.85231, RB_W = 0.40;

function rainbowBand(px, ts) {
  var genesis = Date.UTC(2010, 6, 18);
  var days = (ts - genesis) / 864e5;
  if (days < 400 || px <= 0) return null;
  var mid = Math.exp(RB_A * Math.log(days) + RB_B);
  var ratio = Math.log(px / mid);
  var idx = Math.round(4 - ratio / RB_W);
  idx = Math.max(0, Math.min(8, idx));
  return { i: idx, t: RAINBOW[idx].t, c: RAINBOW[idx].c, mid: mid };
}

/* المعروض المتداول — يُقدَّر من الارتفاع بلا مصدرٍ خارجي.

   المجموع = Σ (مكافأة الحقبة × ‎210,000‎) لكل حقبةٍ مكتملة، زائد ما
   عُدِّن في الحقبة الجارية. والفارق عن الرقم الحقيقي أقلُّ من ‎0.3%‎
   (عملاتٌ مفقودة وكتلٌ لم تُطالب)، وهو لا يغيّر أيَّ قراءة. */
function supplyAt(height) {
  if (!Number.isFinite(height)) return null;
  var total = 0, era = 0;
  while (era * 210000 < height) {
    var inEra = Math.min(210000, height - era * 210000);
    total += inEra * (50 / Math.pow(2, era));
    era++;
    if (era > 33) break;
  }
  return total;
}

