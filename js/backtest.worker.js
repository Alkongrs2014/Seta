importScripts("core.js", "indicators.js", "strategies.js", "backtest.js");

self.onmessage = function (e) {
  var msg = e.data || {};
  if (msg.cmd !== "calibrate") return;
  try {
    var res = calibrateAll(msg.candles, msg.opt || {});
    self.postMessage({ ok: true, result: res });
  } catch (err) {
    self.postMessage({ ok: false, error: String(err && err.message || err) });
  }
};
